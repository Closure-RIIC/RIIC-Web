import assert from "node:assert/strict";
import { register, registerHooks } from "node:module";
import test from "node:test";
import { defaultModelPolicy } from "./model-policy.ts";
import { defaultRatePolicy, parseRatePolicy } from "../billing/rate-policy.ts";
register("../../../../../scripts/ts-path-loader.mjs", import.meta.url);
registerHooks({ resolve(specifier, context, next) { return specifier === "server-only" ? { shortCircuit: true, url: "data:text/javascript,export{}" } : next(specifier, context); } });
const { configuredAgentChoices, selectAgentModel } = await import("./model-catalog.ts");
test("catalog requires an enabled, configured, priced route and an image reservation policy", t => {
  const original = { ...process.env }; t.after(() => { process.env = original; });
  for (const key of Object.keys(process.env)) if (key.startsWith("AGENT_LLM_") || key.startsWith("AGENT_GATEWAY_")) delete process.env[key];
  const policy = defaultModelPolicy(); const rates = defaultRatePolicy("1.2");
  assert.equal(selectAgentModel(undefined, { id: "models:1", policy }, rates).id, "deepseek");
  assert.throws(() => selectAgentModel("arbitrary/upstream", { id: "models:1", policy }, rates));
  assert.equal(configuredAgentChoices(policy, rates)[2].reason, "disabled");
  policy.models[2].enabled = true;
  assert.equal(configuredAgentChoices(policy, rates)[2].reason, "route_unconfigured");
  process.env.AGENT_GATEWAY_MODELS = "deepseek,glm,gpt";
  assert.equal(configuredAgentChoices(policy, rates)[2].reason, "rate_missing");
  rates.models.push({ provider: "riic-gpt", model: "gpt-6.1-sol", input: "10", cachedInput: "2", output: "30", currency: "RMB", exchangeRate: "1" });
  assert.equal(configuredAgentChoices(policy, rates)[2].reason, "image_budget_missing");
  policy.models[2].imageTokensPerImage = 5000;
  process.env.AGENT_LLM_GPT_API_KEY = "private-model-test";
  const selected = selectAgentModel("gpt", { id: "models:2", policy }, rates);
  assert.equal(selected.provider, "riic-gpt"); assert.equal(selected.protocol, "responses");
  assert.equal(selected.policyVersion, "models:2"); assert.equal(selected.vision, true);
  assert.doesNotMatch(JSON.stringify(selected), /private-model-test/);
  assert.doesNotMatch(JSON.stringify(configuredAgentChoices(policy, rates)), /private-model-test/);
  process.env.AGENT_LLM_GPT_MODEL = "supplier-gpt-alias";
  assert.throws(() => selectAgentModel("gpt", { id: "models:2", policy }, rates), /不可用/);
  rates.models.find(row => row.provider === "riic-gpt")!.model = "supplier-gpt-alias";
  assert.equal(selectAgentModel("gpt", { id: "models:2", policy }, rates).model, "supplier-gpt-alias");
  policy.models[2].imageTokensPerImage = 0;
  policy.models[2].imageBudgetMode = "shared-input-limit";
  assert.equal(selectAgentModel("gpt", { id: "models:3", policy }, rates).imageBudgetMode, "shared-input-limit");
  policy.models[2].maxImages = 0;
  assert.equal(configuredAgentChoices(policy, rates)[2].reason, "image_budget_missing");
  policy.models[2].maxImages = 4;
  policy.models[2].imageBudgetMode = "per-image";
  assert.equal(configuredAgentChoices(policy, rates)[2].reason, "image_budget_missing");
});

test("the default text route freezes all priced fallback identities without coupling availability to display prices", t => {
  const original = { ...process.env }; t.after(() => { process.env = original; });
  for (const key of Object.keys(process.env)) if (key.startsWith("AGENT_LLM_") || key.startsWith("AGENT_GATEWAY_")) delete process.env[key];
  process.env.AGENT_GATEWAY_MODELS = "deepseek,glm,gpt";
  process.env.AGENT_GATEWAY_OFFICIAL_FALLBACK_ENABLED = "1";
  const policy = defaultModelPolicy();
  // Disabling a public selector does not rewrite the deployed automatic group.
  policy.models[1].enabled = false;
  const raw = defaultRatePolicy("1.2");
  const rates = parseRatePolicy({ ...raw, models: raw.models.map(row => ({ ...row, peak: null })) });
  const selected = selectAgentModel("deepseek", { id: "models:1", policy }, rates);
  assert.equal(selected.gatewayModel, "group/riic-agent");
  assert.deepEqual(selected.routes?.map(row => row.provider), ["riic-deepseek", "riic-glm", "riic-deepseek-official"]);
  assert.ok(configuredAgentChoices(policy, rates).every(row => !("rates" in row)));
  const missing = { ...rates, models: rates.models.filter(row => row.provider !== "riic-deepseek-official") };
  assert.equal(configuredAgentChoices(policy, missing)[0].reason, "rate_missing");
  assert.throws(() => selectAgentModel("deepseek", { id: "models:1", policy }, missing), /不可用/);
  process.env.AGENT_GATEWAY_MODELS = "deepseek,gpt";
  assert.deepEqual(selectAgentModel("deepseek", { id: "models:1", policy }, rates).routes?.map(row => row.provider), ["riic-deepseek", "riic-deepseek-official"]);
  assert.equal(selected.routes?.length, 3, "an existing selection retains its frozen fallback set");
});
