import { readFile, readdir } from "node:fs/promises";
import path from "node:path";
import { writeGenerated } from "./i18n/write-generated.mjs";

const locales = ["zh-CN", "zh-TW", "en"];
// Keep every public resource entry explicit, like the other workspace exports.
for (const directory of ["packages/arknights-domain", "packages/shell", "packages/endfield-data"]) {
  const file = `${directory}/package.json`;
  const manifest = JSON.parse(await readFile(file, "utf8"));
  delete manifest.exports["./messages/*"];
  for (const locale of locales) {
    for (const name of (await readdir(`${directory}/messages/${locale}`)).sort()) {
      if (name.endsWith(".json")) manifest.exports[`./messages/${locale}/${name}`] = `./messages/${locale}/${name}`;
    }
  }
  await writeGenerated(file, JSON.stringify(manifest, null, 2) + "\n");
}
const sources = {
  arknights: [
    ["apps/arknights/messages", "../../messages"],
    ["packages/arknights-domain/messages", "@riic/arknights-domain/messages"],
    ["packages/shell/messages", "@riic/shell/messages"],
    ["apps/arknights/src/generated/i18n", "../generated/i18n"],
  ],
  endfield: [["apps/endfield/messages", "../../messages"], ["packages/shell/messages", "@riic/shell/messages"], ["packages/endfield-data/messages", "@riic/endfield-data/messages"]],
};
for (const [app, roots] of Object.entries(sources)) {
  const catalogs = [];
  for (const [directory, entry] of roots) {
    for (const file of (await readdir(`${directory}/zh-CN`)).sort().filter(file => file.endsWith(".json"))) {
      const namespace = path.basename(file, ".json");
      // Structured records are not duplicated between the two independent domains.
      const name = namespace === "records" ? directory.startsWith("packages/shell") ? "accountRecords" : "records" : namespace;
      if (catalogs.some(catalog => catalog.name === name)) throw new Error(`Duplicate namespace: ${app}:${name}`);
      catalogs.push({ name, file, entry });
      for (const locale of locales) await readFile(`${directory}/${locale}/${file}`, "utf8");
    }
  }
  for (const locale of locales) {
    const rows = catalogs.map(({ name, file, entry }) => {
      // Simplified Chinese uses the canonical game records already loaded by
      // each feature. Retain the generated catalog for provenance checks only.
      if (app === "arknights" && locale === "zh-CN" && name === "ArknightsGameData") {
        return `  ${JSON.stringify(name)}: () => Promise.resolve({ roomLabels: {}, operatorNames: {}, buildingSkills: {}, itemNames: {} }),`;
      }
      const nested = entry.startsWith(".") ? `../${entry}` : entry;
      return `  ${JSON.stringify(name)}: () => import(${JSON.stringify(`${nested}/${locale}/${file}`)}, { with: { type: "json" } }).then(module => module.default),`;
    });
    await writeGenerated(`apps/${app}/src/i18n/loaders/${locale}.ts`, [
      "// Generated by scripts/generate-i18n-loaders.mjs. One language's import index.",
      "export const loaders: Record<string, () => Promise<unknown>> = {", ...rows, "};", "",
    ].join("\n"));
  }
  const code = [
    "// Generated by scripts/generate-i18n-loaders.mjs. Edit the source JSON catalogs.",
    'import type { AbstractIntlMessages } from "use-intl";',
    'import type { AppLocale } from "@riic/contracts/locale";',
    'import { registerMessages } from "@riic/arknights-domain/i18n/localize";',
    "",
    "const registries: Record<AppLocale, () => Promise<Record<string, () => Promise<unknown>>>> = {",
    ...locales.map(locale => `  ${JSON.stringify(locale)}: () => import(${JSON.stringify(`./loaders/${locale}.ts`)}).then(module => module.loaders),`),
    "};",
    `export const messageNamespaces = ${JSON.stringify(catalogs.map(({ name }) => name))};`,
    "const resources = new Map<string, Promise<unknown>>();",
    "export async function loadMessages(locale: AppLocale, namespaces = messageNamespaces): Promise<AbstractIntlMessages> {",
    "  const loaders = await registries[locale]();",
    "  const entries = await Promise.all(namespaces.map(async namespace => {",
    "    const load = loaders[namespace];",
    "    if (!load) throw new Error(`Unknown message namespace: ${namespace}`);",
    "    const key = `${locale}:${namespace}`;",
    "    let resource = resources.get(key);",
    "    if (!resource) { resource = load().catch(error => { resources.delete(key); throw error; }); resources.set(key, resource); }",
    "    return [namespace, await resource];",
    "  }));",
    "  const messages = Object.fromEntries(entries);",
    "  registerMessages(locale, messages);",
    "  return messages;",
    "}", "",
  ].join("\n");
  await writeGenerated(`apps/${app}/src/i18n/messages.ts`, code);
  // Raw game/record catalogs are accessed through typed data helpers, never ICU calls.
  // Excluding them also prevents use-intl's recursive key types from traversing thousands of game IDs.
  const uiCatalogs = catalogs.filter(({ name }) => !["records", "AccountRecords", "accountRecords", "AgentPersonas", "ArknightsGameData", "EndfieldGameData"].includes(name));
  const types = uiCatalogs.map(({ name, file, entry }) => `import type ${name} from ${JSON.stringify(`${entry}/zh-CN/${file}`)};`);
  types.push(`export type Messages = { ${uiCatalogs.map(({name})=>`${JSON.stringify(name)}: typeof ${name}`).join('; ')} };`, "");
  await writeGenerated(`apps/${app}/src/i18n/message-types.ts`, types.join("\n"));
}
console.log("Generated explicit, independently cached locale/namespace loaders for both applications.");
