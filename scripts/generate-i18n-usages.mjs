import fs from "node:fs/promises";
import path from "node:path";
import { scanHelpers } from "./i18n/x18n-scanner.mjs";
import { writeGenerated } from "./i18n/write-generated.mjs";

async function sources(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => {
    if (entry.isDirectory()) return ["generated", "loaders", "node_modules"].includes(entry.name) ? [] : sources(path.join(directory, entry.name));
    return /\.tsx?$/.test(entry.name) && !/\.test\.|routeTree|message-types|^messages\.ts$/.test(entry.name) ? [path.join(directory, entry.name)] : [];
  }))).flat();
}

// x18n 0.1.2 deduplicates usages by source range. A finite dynamic call can
// reference many keys at one range, so expose each resolved reference separately.
// These manifests are never imported by runtime code and never infer keys from catalogs.
for (const app of ["arknights", "endfield"]) {
  const directories = [`apps/${app}/src`, "packages/shell", ...(app === "arknights" ? ["packages/arknights-domain/src"] : [])];
  const references = new Map();
  for (const file of (await Promise.all(directories.map(sources))).flat().map(file => file.replaceAll("\\", "/")).sort()) {
    const text = await fs.readFile(file, "utf8");
    const relative = file.replaceAll("\\", "/");
    for (const usage of scanHelpers({ path: relative, text }, process.cwd()).usages) {
      if (usage.dynamic === "unknown") throw new Error(`Unresolved i18n reference in ${relative}: ${text.slice(usage.range.start, usage.range.end)}`);
      const id = `${usage.raw}:${usage.dynamic}`;
      if (!references.has(id)) references.set(id, { key: usage.raw, prefix: usage.dynamic === "prefix", source: `${relative}:${text.slice(0, usage.range.start).split("\n").length}` });
    }
  }
  const entries = [...references.values()].sort((a, b) => a.key.localeCompare(b.key, "en"));
  await writeGenerated(`apps/${app}/i18n/usage-manifest.ts`, "// Generated by scripts/generate-i18n-usages.mjs. Development tooling only.\nexport const references = " + JSON.stringify(entries, null, 2) + " as const;\n");
  console.log(`${app}: ${entries.length} explicit translation references`);
}
