import fs from "node:fs";
import path from "node:path";
import { createModuleGraph, normalize } from "./i18n/module-graph.mjs";
import { writeGenerated } from "./i18n/write-generated.mjs";

for (const app of ["arknights", "endfield"]) {
  const appRoot = `apps/${app}/src`, routeRoot = `${appRoot}/routes`;
  const loader = fs.readFileSync(`${appRoot}/i18n/messages.ts`, "utf8");
  const namespaces = new Set(JSON.parse(loader.match(/export const messageNamespaces = (\[[^\n]+\]);/)[1]));
  const graph = createModuleGraph(namespaces), entries = new Set(), routes = [];
  for (const file of fs.readdirSync(appRoot, { recursive: true }).filter(f => /\.tsx$/.test(f))) {
    const absolute = path.resolve(appRoot, file), source = fs.readFileSync(absolute, "utf8");
    const route = source.match(/createFileRoute\("([^"]+)"\)/)?.[1];
    if (route || file === "routes/__root.tsx" || file === "routes\\__root.tsx") {
      entries.add(absolute); if (route) routes.push({ route, module: normalize(path.relative(process.cwd(), absolute)) });
    }
    for (const target of graph.inspect(absolute).dynamic) if (/\.[cm]?tsx?$/.test(target)) entries.add(target);
    for (const match of source.matchAll(/(?:withMessages|lazyWithMessages)\([\s\S]*?"((?:apps|packages)\/[^"\n]+)"\)/g)) entries.add(path.resolve(match[1]));
  }
  const features = Object.fromEntries([...entries].sort().map(file => [normalize(path.relative(process.cwd(), file)), [...graph.resources(file)].sort()]));
  const rootId = `${routeRoot}/__root.tsx`;
  const root = [...new Set([...(features[rootId] ?? []), ...["Common", "Metadata", "AccountMenu", "Shell_GameSwitcher", "Interface"].filter(n => namespaces.has(n))])].sort();
  // Resource names repeat across routes and lazy features. Store a compact index
  // in the initial graph, while exposing the same readable runtime contract.
  const names = [...new Set(Object.values(features).flat())].sort();
  const groups = [], groupIds = new Map();
  const index = Object.fromEntries(Object.entries(features).map(([feature, resources]) => {
    const ids = resources.map(name => names.indexOf(name)), key = JSON.stringify(ids);
    if (!groupIds.has(key)) { groupIds.set(key, groups.length); groups.push(ids); }
    return [feature, groupIds.get(key)];
  }));
  const code = `// Generated by scripts/generate-i18n-features.mjs from explicit module dependencies.
import { routeMessageNamespaces } from "@riic/shell/route-resources";
const names = ${JSON.stringify(names)};
const groups = ${JSON.stringify(groups)}.map(group => group.map(id => names[id]!));
const index: Record<string, number> = ${JSON.stringify(index,null,2)};
export const features: Record<string, readonly string[]> = Object.fromEntries(Object.entries(index).map(([feature, group]) => [feature, groups[group]!]));
export const rootNamespaces = ${JSON.stringify(root)};
const routes = ${JSON.stringify(routes,null,2)};
export function pageNamespaces(pathname: string): string[] { return routeMessageNamespaces(pathname, routes, features, rootNamespaces); }
`;
  await writeGenerated(`${appRoot}/i18n/feature-manifest.ts`, code);
  console.log(`${app}: ${Object.keys(features).length} features; ${root.length}/${namespaces.size} root namespaces`);
}
